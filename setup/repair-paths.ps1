#Requires -Version 5.1
# Install/update a standalone runtime, independent of the source folder location.
$ErrorActionPreference = 'Stop'
$SourceDir = Split-Path $PSScriptRoot -Parent
$InstallDir = Join-Path ([Environment]::GetFolderPath('LocalApplicationData')) 'Programs\Shuffles'
$RuntimeFiles = @('shuffles.py', 'shuffles.bat',
    'installer.ps1', 'uninstaller.ps1', 'setup\repair-paths.ps1', 'setup\setup.bat')
foreach ($file in $RuntimeFiles) {
    if (-not (Test-Path -LiteralPath (Join-Path $SourceDir $file) -PathType Leaf)) {
        throw "Required file missing: $file"
    }
}
$PythonCommand = Get-Command python.exe -ErrorAction SilentlyContinue
$PythonExe = if ($PythonCommand) { $PythonCommand.Source } else { $null }
if (-not $PythonExe -and (Test-Path -LiteralPath (Join-Path $SourceDir 'python-path.txt'))) {
    $PythonExe = [IO.File]::ReadAllText((Join-Path $SourceDir 'python-path.txt')).Trim()
}
if (-not $PythonExe -or -not (Test-Path -LiteralPath $PythonExe -PathType Leaf)) {
    throw 'Python unavailable: install Python 3.10+ or restore the configured interpreter.'
}
& $PythonExe -c 'import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)'
if ($LASTEXITCODE -ne 0) { throw 'A working Python 3.10+ installation is required.' }
$PythonWindowExe = Join-Path (Split-Path $PythonExe -Parent) 'pythonw.exe'
if (-not (Test-Path -LiteralPath $PythonWindowExe -PathType Leaf)) {
    throw 'pythonw.exe must be installed beside python.exe for the hidden context-menu launch.'
}
$WindowValidation = "import subprocess,sys;sys.exit(subprocess.call([sys.argv[1],'-c','import sys;sys.exit(0 if sys.version_info >= (3,10) else 1)']))"
& $PythonExe -c $WindowValidation $PythonWindowExe
if ($LASTEXITCODE -ne 0) { throw 'The windowless Python interpreter failed validation.' }
New-Item -ItemType Directory -Path (Join-Path $InstallDir 'setup') -Force | Out-Null
if ([IO.Path]::GetFullPath($SourceDir).TrimEnd('\') -ne [IO.Path]::GetFullPath($InstallDir).TrimEnd('\')) {
    foreach ($file in $RuntimeFiles) {
        Copy-Item -LiteralPath (Join-Path $SourceDir $file) -Destination (Join-Path $InstallDir $file) -Force
    }
}

# Pin the validated interpreter for batch/legacy callers too. Explorer can have
# an older PATH than this installer process; quiet mode needs console stdout.
[IO.File]::WriteAllText((Join-Path $InstallDir 'python-path.txt'), $PythonExe, [Text.UTF8Encoding]::new($false))

# Resolve the batch file relative to the launcher rather than embedding its path.
$vbsContent = @'
' Generated by setup\repair-paths.ps1. Independent of the source checkout.
Option Explicit
Dim shell, fso, base, reader, python, script, cmd
Set shell = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
If WScript.Arguments.Count <> 1 Then WScript.Quit 1
base = fso.GetParentFolderName(WScript.ScriptFullName)
script = fso.BuildPath(base, "shuffles.py")
If Not fso.FileExists(fso.BuildPath(base, "python-path.txt")) Then
    MsgBox "Shuffles runtime is missing. Run setup\repair-paths.ps1 to reinstall.", 16, "Shuffles"
    WScript.Quit 1
End If
Set reader = fso.OpenTextFile(fso.BuildPath(base, "python-path.txt"), 1)
python = Trim(reader.ReadAll)
reader.Close
python = fso.BuildPath(fso.GetParentFolderName(python), "pythonw.exe")
cmd = """" & python & """ """ & script & """ """ & WScript.Arguments(0) & "\."""
WScript.Quit shell.Run(cmd, 0, True)
'@
$VbsPath = Join-Path $InstallDir 'hide_and_run.vbs'
[IO.File]::WriteAllText($VbsPath, $vbsContent, [Text.UTF8Encoding]::new($false))
function Reg-Escape([string]$Value) { $Value.Replace('\', '\\').Replace('"', '\"') }
# Shell launches Python directly: no PATH probe, CMD parsing, or VBScript required.
# The appended \. prevents a trailing backslash (drive roots) escaping the quote.
$Command = '"{0}" "{1}" "%V\."' -f $PythonWindowExe, (Join-Path $InstallDir 'shuffles.py')
# Windows' own yellow folder icon; independent of custom icon assets.
$Icon = (Join-Path $env:SystemRoot 'System32\shell32.dll') + ',3'
$EscCommand = Reg-Escape $Command
$EscIcon = Reg-Escape $Icon
$regContent = @"
Windows Registry Editor Version 5.00

[HKEY_CURRENT_USER\Software\Classes\Directory\Background\shell\ShufflesOrganize]
@="Organize this folder"
"Icon"="$EscIcon"

[HKEY_CURRENT_USER\Software\Classes\Directory\Background\shell\ShufflesOrganize\command]
@="$EscCommand"

"@

$RegFile = Join-Path $InstallDir 'setup\setup.reg'
[IO.File]::WriteAllText($RegFile, $regContent, [Text.Encoding]::Unicode)
& reg.exe import $RegFile | Out-Host
if ($LASTEXITCODE -ne 0) { throw "reg import failed: $LASTEXITCODE" }
$Key = 'HKCU:\Software\Classes\Directory\Background\shell\ShufflesOrganize'
if ((Get-Item -LiteralPath "$Key\command").GetValue('') -ne $Command) {
    throw 'Registry command verification failed.'
}
if ((Get-Item -LiteralPath $Key).GetValue('Icon') -ne $Icon) {
    throw 'Registry icon verification failed.'
}
Write-Host "Installed Shuffles runtime: $InstallDir"
Write-Host 'Source-folder moves no longer require context-menu repair.'
